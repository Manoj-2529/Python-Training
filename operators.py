#arithmetic operations
x=41
y=46
print(f"Addition : {x+y}")
print(f"Subtraction: {x-y}")
print(f"Multiplication: {x*y}")
print(f"Division: {x/y}")
print(f"Modulo division {x%y}")
print(f"Positive floor division is {x//y}")
print(f"Positive floor division is {-x//y}")
print(f"Exponentiation: {x**y}")


#relational Operations
print(10<2)
print(10>2)
print(10<=2)
print(10>=2)
print(10==2)
print(10!=2)



#assignment operations
num=46
print(f"num = {num}")
num+=10
print(f"num += 10 : {num}")
num-=10
print(f"num -= 10 : {num}")
num*=30
print(f"num *= 30 : {num}")
num/=30
print(f"num /= 30 : {num}")
num%=30
print(f"num %= 30 : {num}")
num//=30
print(f"num //= 30 : {num}")
num**=30
print(f"num **= 30 : {num}")

#logical operations
num=10
num1=20
print('~a=',~num)
print('a&b=',num&num1)
print('a | b=',num | num1)
print('a^b=',num ^ num1)
print('a>>1',num>>1)
print('a<<1',num<<1)